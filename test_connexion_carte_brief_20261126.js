// Carte « Connexion indisponible » du Brief : libellés exacts, aucun bouton, rôle gérant/manager.
const fs = require('fs'), assert = require('assert');
const src = fs.readFileSync(__dirname + '/NEXUS-Brief-v1.html', 'utf8');
const debut = src.indexOf('function heureAlerteConnexion');
const fin = src.indexOf('// Alerte « sonde à vérifier »');
assert(debut > 0 && fin > debut, 'bloc introuvable');
const bloc = src.slice(debut, fin);
const fabrique = new Function('state', 'let ALERTE_CONNEXION = state.a, ROLE_REEL_COURANT = state.r, FUSEAU_STATION = "UTC";' + bloc + 'return renderAlerteConnexion();');
let ok = 0; const v = (c, m) => { assert(c, m); ok++; };
const iso = '2026-11-26T07:05:00Z';
const g = fabrique({ a: { lecture: true, nombre: 4, premier: iso }, r: 'gerant' });
const m = fabrique({ a: { lecture: true, nombre: 4, premier: iso }, r: 'manager' });
v(g.includes('La connexion a échoué 4 fois depuis 07 h 05. Prévenez NEXUS Conseil si cela dure plus de 15 minutes.'), 'libellé gérant');
v(m.includes('La connexion a échoué 4 fois depuis 07 h 05. Prévenez le gérant et évitez de multiplier les essais.'), 'libellé manager');
v(!/<button|<a |onclick/i.test(g + m), 'aucun bouton ni lien');
v(!/red|#f00|#e|emoji|[\u{1F300}-\u{1FAFF}]/u.test(g), 'pas de rouge ni emoji');
const feuille = src.match(/\.alerte-connexion\{[^}]*\}/)[0];
const neutre = fabrique({ a: { lecture: false }, r: 'gerant' });
v(/var\(--amber-dim\)/.test(feuille) && /var\(--amber\)/.test(feuille), 'jetons ambre dans la feuille');
v(!/rgba?\(|#[0-9a-f]{3,8}\b/i.test(feuille), 'point 1 : aucune couleur en dur');
v(/border-radius:12px/.test(feuille) && !/border-radius:10px/.test(src.slice(debut, fin)), 'point 2 : rayon 12 px');
v(!/style=/.test(g + m + neutre), 'point 3 : aucun style en ligne');
v(/\.alerte-connexion\.neutre\{[^}]*color:var\(--text-dim\)/.test(src) && !/amber/.test(src.match(/\.alerte-connexion\.neutre\{[^}]*\}/)[0]), 'point 4 : ligne neutre sans ambre');
v(/\.section\{padding:20px 20px;\}/.test(src) && /margin:0 20px 10px/.test(feuille), 'marges latérales de la carte alignées sur celles de la carte Boussole (20 px)');
v(neutre.includes('neutre'), 'ligne neutre classée neutre');
v(!/déjà connectées/.test(g + m + neutre), 'phrase non démontrée retirée');
v(fabrique({ a: null, r: 'gerant' }) === '', 'absente si tout va bien');
v(fabrique({ a: { lecture: false }, r: 'gerant' }).includes('lecture impossible'), 'ligne neutre');
v(/action: 'alerte_indisponible'/.test(src), 'action appelée');
console.log('test_connexion_carte_brief_20261126 : ' + ok + ' vérifications OK');
